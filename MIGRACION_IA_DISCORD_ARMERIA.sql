-- Tablas adicionales; no elimina ni modifica datos existentes.
CREATE TABLE IF NOT EXISTS nexus_settings (
 setting_key VARCHAR(80) NOT NULL PRIMARY KEY,
 value TEXT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS discord_media_publications (
 media_id INT UNSIGNED NOT NULL PRIMARY KEY,
 channel_id VARCHAR(32) NULL,
 message_id VARCHAR(32) NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending',
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 last_error VARCHAR(500) NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS armory_characters (
 profile_id INT UNSIGNED NOT NULL PRIMARY KEY,
 slug VARCHAR(120) NOT NULL,
 name VARCHAR(120) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
